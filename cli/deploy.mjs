// @ts-check
// `intersite deploy [--dry-run]`: provisions D1, applies the schema, sets missing tokens, deploys the collector Worker.
import { spawnSync } from "node:child_process";
import { randomBytes } from "node:crypto";
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

import { loadConfig } from "../shared/config.mjs";

const collectorDir = new URL("../collector/", import.meta.url);
const workerPath = fileURLToPath(new URL("worker.mjs", collectorDir));
const schemaPath = fileURLToPath(new URL("schema.sql", collectorDir));
const compatibilityDate = /"compatibility_date":\s*"([^"]+)"/.exec(readFileSync(new URL("wrangler.jsonc", collectorDir), "utf8"))?.[1];
const WRANGLER = ["npx", "--yes", "wrangler@4"];

/** @param {string[]} argv @param {{ cwd: string }} context @returns {Promise<number>} */
export default async function deploy(argv, { cwd }) {
  const unknown = argv.find((arg) => arg !== "--dry-run");
  if (unknown) {
    console.error(`unknown option ${unknown}; usage: intersite deploy [--dry-run]`);
    return 2;
  }
  const dryRun = argv.includes("--dry-run");
  /** @type {import("../shared/config.mjs").Config} */
  let config;
  try {
    config = loadConfig(cwd);
  } catch (error) {
    console.error(String(/** @type {Error} */ (error).message));
    return 2;
  }
  const { name, domain, readTokenEnv, ingestTokenEnv, dailyCap } = config.collector;
  const outDir = join(cwd, ".intersite");
  const configPath = join(outDir, "wrangler.jsonc");
  const secretsPath = join(outDir, "secrets.json");
  const c = ["-c", configPath];

  /** Runs wrangler with stdout captured (and echoed when `show`). @param {string[]} args @param {boolean} [show] */
  const wrangler = (args, show = false) => {
    const result = spawnSync(WRANGLER[0], [...WRANGLER.slice(1), ...args], { cwd, encoding: "utf8", stdio: ["inherit", "pipe", "pipe"] });
    if (show) process.stdout.write(result.stdout ?? "");
    return { ok: result.status === 0, out: `${result.stdout ?? ""}${result.stderr ?? ""}`, stdout: result.stdout ?? "" };
  };
  /** @param {string[]} args */
  const show = (args) => [...WRANGLER, ...args].map((arg) => (/^[\w@./:=,-]+$/.test(arg) ? arg : JSON.stringify(arg))).join(" ");

  /** @param {string} databaseId */
  const writeConfig = (databaseId) => {
    const generated = {
      name,
      main: workerPath,
      compatibility_date: compatibilityDate,
      d1_databases: [{ binding: "DB", database_name: name, database_id: databaseId }],
      triggers: { crons: ["17 3 * * *"] },
      vars: { DAILY_CAP_OK: String(dailyCap.ok), DAILY_CAP_OTHER: String(dailyCap.other) },
      ...(domain ? { routes: [{ pattern: domain, custom_domain: true }] } : {}),
    };
    const text = `// Generated by intersite deploy; edit intersite.yml instead.\n${JSON.stringify(generated, null, 2)}\n`;
    mkdirSync(outDir, { recursive: true });
    writeFileSync(configPath, text);
    return text;
  };

  const deployArgs = ["deploy", ...c];
  if (dryRun) {
    console.log(`config ${configPath}:`);
    process.stdout.write(writeConfig("<uuid of D1 database " + name + ">"));
    console.log("would run:");
    for (const args of [
      ["d1", "list", "--json"],
      ["d1", "create", name, "(only when the list has no database named " + name + ")"],
      ["d1", "execute", "DB", "--remote", "--file", schemaPath, "--yes", ...c],
      ["secret", "list", "--format", "json", ...c],
      [...deployArgs, "--secrets-file", secretsPath, "(only with tokens not yet set)"],
    ]) {
      console.log(`  ${show(args)}`);
    }
    return 0;
  }

  /** @returns {string | undefined} */
  const findDatabase = () => {
    const listed = wrangler(["d1", "list", "--json"]);
    if (!listed.ok) throw new Error(`wrangler d1 list failed:\n${listed.out}`);
    return JSON.parse(listed.stdout).find((/** @type {any} */ db) => db.name === name)?.uuid;
  };

  try {
    let databaseId = findDatabase();
    if (!databaseId) {
      const created = wrangler(["d1", "create", name]);
      if (!created.ok) throw new Error(`wrangler d1 create ${name} failed:\n${created.out}`);
      databaseId = findDatabase();
      if (!databaseId) throw new Error(`D1 database ${name} was created but is not listed`);
    }
    writeConfig(databaseId);

    const schema = wrangler(["d1", "execute", "DB", "--remote", "--file", schemaPath, "--yes", ...c]);
    if (!schema.ok) throw new Error(`applying the schema failed:\n${schema.out}`);

    const listed = wrangler(["secret", "list", "--format", "json", ...c]);
    if (!listed.ok && !/not found/i.test(listed.out)) throw new Error(`wrangler secret list failed:\n${listed.out}`);
    const existing = new Set(listed.ok ? JSON.parse(listed.stdout).map((/** @type {any} */ secret) => secret.name) : []);
    /** @type {Record<string, string>} */
    const fresh = {};
    for (const secret of ["INGEST_TOKEN", "READ_TOKEN"]) if (!existing.has(secret)) fresh[secret] = randomBytes(32).toString("base64url");

    // Secrets ride along with the deploy, so the Worker never serves without them.
    if (Object.keys(fresh).length) writeFileSync(secretsPath, JSON.stringify(fresh), { mode: 0o600 });
    let deployed;
    try {
      deployed = wrangler(Object.keys(fresh).length ? [...deployArgs, "--secrets-file", secretsPath] : deployArgs, true);
    } finally {
      rmSync(secretsPath, { force: true });
    }
    if (!deployed.ok) throw new Error(`wrangler deploy failed:\n${deployed.out}`);

    const url = domain ? `https://${domain}` : /https:\/\/\S+\.workers\.dev/.exec(deployed.out)?.[0];
    if (fresh.INGEST_TOKEN) console.log(`store once, shown only now: ${ingestTokenEnv}=${fresh.INGEST_TOKEN}`);
    if (fresh.READ_TOKEN) console.log(`store once, shown only now: ${readTokenEnv}=${fresh.READ_TOKEN}`);
    if (!url) {
      console.log("deployed; find the Worker URL in the wrangler output above");
      return 0;
    }
    console.log(`collector ${url}`);
    console.log(`put in intersite.yml: collector: { url: "${url}" }`);
    return 0;
  } catch (error) {
    console.error(/** @type {Error} */ (error).message);
    console.error("rerun: intersite deploy");
    return 2;
  }
}

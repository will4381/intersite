// @ts-check
import { defineRule } from "@oxlint/plugins";

import { isGenerated } from "./shared.mjs";

// A bare `eslint-disable` (no rule names) silences this rule too, because oxlint honors it before any rule runs;
// cli/lint.mjs catches those with a text scan, reported as no-bare-suppression.
const suppression = /^\s*(@ts-ignore|@ts-nocheck|eslint-disable|oxlint-disable)/;
/** The one allowed form: a single line, a named rule, and a written reason. */
const reasoned = /^\s*(?:eslint|oxlint)-disable(?:-next-line|-line)\s+\S.*\s--\s+\S/;
/** A reasoned range, allowed when the file switches the same rules back on: `/* oxlint-disable rule -- why *\/` ... `/* oxlint-enable rule *\/`. */
const range = /^\s*(eslint|oxlint)-disable\s+(\S.*?)\s+--\s+\S/;

/** `@ts-expect-error` with nothing after it: a type error silenced with no word on why it is expected. */
const bareExpectError = /^\s*@ts-expect-error\s*$/;

export const id = "no-lint-suppression";
export const pack = "slop";

export const rule = defineRule({
  meta: {
    type: "problem",
    messages: {
      found: "This comment silences the type checker or linter instead of fixing the problem. Remove it and fix the code it hides. For a deliberate exception, use `// oxlint-disable-next-line <rule> -- <why>` (or a `-- <why>` disable closed by a matching `oxlint-enable <rule>`), or `// @ts-expect-error <why>` for a type error the code means to cause.",
    },
  },
  createOnce(context) {
    return {
      // A generated client carries the generator's own `@ts-ignore`s; nobody edits it, the generator owns them.
      before: () => !isGenerated(context),
      Program() {
        const comments = context.sourceCode.getAllComments();
        comments.forEach((comment, i) => {
          const text = comment.value;
          if (!(suppression.test(text) && !reasoned.test(text)) && !bareExpectError.test(text)) return;
          const [, tool, rules] = range.exec(text) ?? [];
          if (rules && comments.slice(i + 1).some((c) => c.value.trim() === `${tool}-enable ${rules}`)) return;
          context.report({ loc: comment.loc, messageId: "found" });
        });
      },
    };
  },
});

export const bad = [
  "// @ts-ignore\nconst n: number = 'x';",
  "/* eslint-disable no-console */\nrun();",
  "run(); // oxlint-disable-line no-console",
  "// @ts-nocheck\nrun();",
  "// oxlint-disable-next-line no-console\nrun();",
  "/* eslint-disable no-console -- everywhere */\nrun();",
  "// @ts-expect-error\nconst n: number = 'x';",
  "/* oxlint-disable no-await-in-loop -- one transaction runs one query at a time */\nfor (const a of actions) await run(a);",
];

export const good = [
  "// The cache is warmed on boot, see boot.ts.\nrun();",
  "// @ts-expect-error testing that bad input is rejected\nparse(1);",
  "// oxlint-disable-next-line no-console -- printing is this command's output\nrun();",
  "/* oxlint-disable no-await-in-loop -- one transaction runs one query at a time */\nfor (const a of actions) await run(a);\n/* oxlint-enable no-await-in-loop */",
  "// This file is auto-generated by @hey-api/openapi-ts\n\n// @ts-ignore\nexport const x = 1;",
];
